// Helper to convert StructuredVehicle to legacy CarProps for full component backward compatibility
export const structuredToCarProps = (v: StructuredVehicle) => ({
  city_mpg: v.is_electric ? 115 : v.engine.cylinders === 8 ? 16 : v.engine.cylinders === 6 ? 20 : 28,
  class: v.body_type.toLowerCase(),
  combination_mpg: v.is_electric ? 110 : v.engine.cylinders === 8 ? 19 : v.engine.cylinders === 6 ? 24 : 32,
  cylinders: v.engine.cylinders || 4,
  displacement: parseFloat(v.engine.displacement) || 2.0,
  drive: v.drivetrain.toLowerCase(),
  fuel_type: v.fuel_type.toLowerCase(),
  highway_mpg: v.is_electric ? 105 : v.engine.cylinders === 8 ? 24 : v.engine.cylinders === 6 ? 29 : 38,
  make: v.make,
  model: v.model,
  transmission: v.transmission.toLowerCase().startsWith("m") ? "m" : "a",
  year: v.year,
  price: v.daily_rental_price ? v.daily_rental_price * 320 : 25000,
  mileage: Math.max(1000, (2026 - v.year) * 11000),
  location: v.country_of_origin === "Germany" ? "Miami FL" : v.country_of_origin === "Japan" ? "Los Angeles CA" : "New York NY",
  body_type: v.body_type,
  id: v.id,
  status: v.availability ? ("available" as const) : ("rented" as const),
  generation: v.generation,
  trim: v.trim,
  vehicle_class: v.vehicle_class,
  seating_capacity: v.seating_capacity,
  doors: v.doors,
  color: v.color,
  is_electric: v.is_electric,
  is_hybrid: v.is_hybrid,
  daily_rental_price: v.daily_rental_price,
  image_url: v.image.url
});
